test('drops a $ref sibling to a concrete additionalProperties schema', async () => {
  nock('https://www.schemastore.org')
    .get('/api/json/catalog.json')
    .reply(200, {
      $schema: 'https://json.schemastore.org/schema-catalog.json',
      version: 1,
      schemas: [
        {
          name: 'Aliased',
          description: 'Aliased schema description',
          url: 'https://example.com/aliased.json',
        },
      ],
    })

  nock('https://example.com')
    .get('/aliased.json')
    .reply(200, {
      $schema: 'http://json-schema.org/draft-07/schema#',
      title: 'Aliased Schema',
      type: 'object',
      properties: {
        name: {
          type: 'string',
        },
        registryAliases: {
          $ref: '#/definitions/registryAliases',
        },
      },
      definitions: {
        registryAliases: {
          type: 'object',
          // A schema that both self-references the root (as Renovate's
          // `registryAliases` does, mirroring its recursive per-manager
          // overrides) and declares a concrete `additionalProperties`
          // would otherwise compile into an interface whose inherited
          // `name` property conflicts with its own string index
          // signature.
          $ref: '#',
          additionalProperties: {
            type: 'string',
          },
        },
      },
    })

  const ts = await compile('aliased')

  expect(ts).toMatchInlineSnapshot(`
    "/* eslint-disable */
    /**
     * This file was automatically generated by json-schema-to-typescript.
     * DO NOT MODIFY IT BY HAND. Instead, modify the source JSONSchema file,
     * and run json-schema-to-typescript to regenerate this file.
     */

    export interface Aliased {
      name?: string;
      registryAliases?: RegistryAliases;
      [k: string]: unknown;
    }
    export interface RegistryAliases {
      [k: string]: string;
    }
    "
  `)
})

